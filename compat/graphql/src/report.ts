import type { ImplementationReport, Status } from "./compare.js";

const ICON: Record<Status, string> = { pass: "pass", fail: "FAIL", skipped: "skipped" };

type Tally = Record<Status, number>;

function emptyTally(): Tally {
  return { pass: 0, fail: 0, skipped: 0 };
}

function featureStatus(t: Tally): string {
  if (t.fail > 0) return "FAIL";
  if (t.pass === 0) return "skipped";
  return t.skipped > 0 ? "partial" : "pass";
}

/** Renders the markdown compatibility report (`REPORT.md`). Deterministic: no timestamps. */
export function renderReport(
  reports: ImplementationReport[],
  meta: { referenceVersion: string },
): string {
  const lines: string[] = [];
  lines.push("# GraphQL compatibility report");
  lines.push("");
  lines.push(
    `Generated by \`pnpm --filter compat-graphql report\`. Do not edit. Goldens come from \`@neo4j/graphql@${meta.referenceVersion}\`.`,
  );
  lines.push("");

  lines.push("## Summary");
  lines.push("");
  lines.push("| Implementation | Pass | Fail | Skipped | Note |");
  lines.push("| --- | ---: | ---: | ---: | --- |");
  for (const r of reports) {
    const t = emptyTally();
    for (const f of r.fixtures) for (const c of f.checks) t[c.status]++;
    lines.push(
      `| \`${r.implementation}\` | ${t.pass} | ${t.fail} | ${t.skipped} | ${r.skipReason ?? ""} |`,
    );
  }
  lines.push("");

  const features = new Map<string, Map<string, Tally>>();
  for (const r of reports) {
    for (const f of r.fixtures) {
      for (const c of f.checks) {
        for (const feature of c.features) {
          const byImpl = features.get(feature) ?? new Map<string, Tally>();
          const t = byImpl.get(r.implementation) ?? emptyTally();
          t[c.status]++;
          byImpl.set(r.implementation, t);
          features.set(feature, byImpl);
        }
      }
    }
  }
  lines.push("## By feature");
  lines.push("");
  lines.push(`| Feature | ${reports.map((r) => `\`${r.implementation}\``).join(" | ")} |`);
  lines.push(`| --- | ${reports.map(() => "---").join(" | ")} |`);
  for (const feature of [...features.keys()].sort()) {
    const byImpl = features.get(feature)!;
    const cells = reports.map((r) => {
      const t = byImpl.get(r.implementation) ?? emptyTally();
      return `${featureStatus(t)} (${t.pass}/${t.pass + t.fail + t.skipped})`;
    });
    lines.push(`| ${feature} | ${cells.join(" | ")} |`);
  }
  lines.push("");

  lines.push("## By operation");
  lines.push("");
  const fixtureNames = reports[0]?.fixtures.map((f) => f.fixture) ?? [];
  for (const fixture of fixtureNames) {
    lines.push(`### ${fixture}`);
    lines.push("");
    lines.push(
      `| Check | Features | ${reports.map((r) => `\`${r.implementation}\``).join(" | ")} |`,
    );
    lines.push(`| --- | --- | ${reports.map(() => "---").join(" | ")} |`);
    const checks = reports[0]!.fixtures.find((f) => f.fixture === fixture)!.checks;
    for (const check of checks) {
      const cells = reports.map((r) => {
        const c = r.fixtures
          .find((f) => f.fixture === fixture)
          ?.checks.find((x) => x.check === check.check);
        if (!c) return "-";
        return c.status === "fail" && c.detail
          ? `${ICON.fail}: ${c.detail.replace(/\|/g, "\\|").split("\n")[0]}`
          : ICON[c.status];
      });
      lines.push(`| ${check.check} | ${check.features.join(", ")} | ${cells.join(" | ")} |`);
    }
    lines.push("");
  }
  return lines.join("\n");
}
