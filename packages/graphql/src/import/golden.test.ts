import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { parseSchema, renderCyphraGenSource, resolveSchema, validateSchema } from "@cyphra/schema";
import { describe, expect, it } from "vitest";
import { convertGraphQLTypeDefs } from "./convert.js";
import { formatImportReport, printImportedSchema } from "./print.js";

const FIXTURES = join(import.meta.dirname, "__fixtures__");

describe.each(["movies", "blog", "shop", "library"])("golden: %s", (name) => {
  it("converts to the expected schema and report", async () => {
    const body = await readFile(join(FIXTURES, `${name}.graphql`), "utf8");
    const result = convertGraphQLTypeDefs([{ name: `${name}.graphql`, body }]);
    const schema = printImportedSchema(result);
    await expect(schema).toMatchFileSnapshot(join(FIXTURES, `${name}.cyphra`));
    await expect(`${formatImportReport(result.issues)}\n`).toMatchFileSnapshot(
      join(FIXTURES, `${name}.report.txt`),
    );

    // Round trip: the output parses, validates, resolves and generates a client.
    const doc = parseSchema(schema);
    validateSchema(doc);
    const model = resolveSchema(doc);
    expect(model.nodes.length).toBeGreaterThan(0);
    expect(renderCyphraGenSource(doc)).toContain("Generated by `cyphra generate`");
  });
});
