import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { parseSchema, renderCyphraGenSource, resolveSchema, validateSchema } from "@cyphra/schema";
import { describe, expect, it } from "vitest";
import { convertGraphQLTypeDefs, type GraphQLImportOptions } from "./convert.js";
import { formatImportReport, printImportedSchema } from "./print.js";

const FIXTURES = join(import.meta.dirname, "__fixtures__");

/** Options of the fixtures converted as if `cyphra import graphql --url` read a database. */
const OPTIONS: Record<string, GraphQLImportOptions> = {
  ids: {
    constraints: [
      { name: "user_id", label: "User", properties: ["id"], type: "UNIQUE" },
      { name: "user_email", label: "User", properties: ["email"], type: "UNIQUE" },
      { name: "user_handle", label: "User", properties: ["handle"], type: "UNIQUE" },
      { name: "team_slug", label: "Team", properties: ["slug"], type: "UNIQUE" },
      { name: "tenant_id", label: "Tenant", properties: ["id"], type: "KEY" },
      { name: "workspace_code", label: "Workspace", properties: ["code"], type: "UNIQUE" },
      { name: "org_region_code", label: "Org", properties: ["region", "code"], type: "UNIQUE" },
      { name: "legacy_ref", label: "Legacy", properties: ["ref"], type: "UNIQUE" },
    ],
    idFields: ["Tag.id"],
  },
  "mixed-ids": { idFields: ["Activity.id"] },
};

describe.each(["movies", "blog", "shop", "library", "search", "labels", "ids", "mixed-ids"])(
  "golden: %s",
  (name) => {
    it("converts to the expected schema and report", async () => {
      const body = await readFile(join(FIXTURES, `${name}.graphql`), "utf8");
      const result = convertGraphQLTypeDefs([{ name: `${name}.graphql`, body }], OPTIONS[name]);
      const schema = printImportedSchema(result);
      await expect(schema).toMatchFileSnapshot(join(FIXTURES, `${name}.cyphra`));
      await expect(`${formatImportReport(result.issues)}\n`).toMatchFileSnapshot(
        join(FIXTURES, `${name}.report.txt`),
      );

      // Round trip: the output parses, validates, resolves and generates a client.
      const doc = parseSchema(schema);
      validateSchema(doc);
      const model = resolveSchema(doc);
      expect(model.nodes.length).toBeGreaterThan(0);
      expect(renderCyphraGenSource(doc)).toContain("Generated by `cyphra generate`");
    });
  },
);
