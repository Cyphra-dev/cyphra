import { access, writeFile } from "node:fs/promises";
import path from "node:path";
import { introspectDatabase, schemaFromIntrospection } from "@cyphra/migrator";
import { parseSchema, printSchemaDocument, resolveSchema } from "@cyphra/schema";
import type { CyphraConfig } from "../config.js";
import { clientFromEnv } from "../clientFromEnv.js";

/**
 * `cyphra pull`: introspect the database (read-only) and write a `.cyphra` schema.
 */
export async function runPull(
  cwd: string,
  config: CyphraConfig,
  opts: { force?: boolean; print?: boolean },
): Promise<void> {
  const client = clientFromEnv(false);
  let source: string;
  let warnings: string[];
  try {
    const result = schemaFromIntrospection(await introspectDatabase(client));
    warnings = result.warnings;
    const header = [
      "// Generated by `cyphra pull`. Review it: relation names are guessed from relationship types,",
      "// every relation is to-many, and required-ness reflects the data at the time of the pull.",
      "",
      "",
    ].join("\n");
    source = header + printSchemaDocument(result.doc);
  } finally {
    await client.close();
  }
  // The output must round-trip through our own parser and resolver.
  resolveSchema(parseSchema(source));

  if (opts.print) {
    process.stdout.write(source);
  } else {
    const exists = await access(config.schema).then(
      () => true,
      () => false,
    );
    if (exists && !opts.force) {
      throw new Error(
        `${path.relative(cwd, config.schema)} already exists: pass --force to overwrite or --print to write to stdout.`,
      );
    }
    await writeFile(config.schema, source, "utf8");
    console.log(`Wrote ${path.relative(cwd, config.schema)}`);
  }
  for (const w of warnings) console.warn(`warning: ${w}`);
}
