import type { MigrationPlan } from "./diff.js";

/** Options for {@link renderMigrationSource}. */
export type RenderMigrationOptions = {
  /** Migration name (also the file stem). */
  readonly name: string;
  /** Module to import `defineMigration` from (default `"cyphra"`). */
  readonly runtimeImport?: string;
};

function indentComment(text: string, indent: string): string[] {
  return text.split("\n").map((l) => `${indent}// ${l}`);
}

function call(cypher: string, params?: Readonly<Record<string, unknown>>): string {
  const p = params && Object.keys(params).length ? `, ${JSON.stringify(params)}` : "";
  return `await db.execute(${JSON.stringify(cypher)}${p});`;
}

/**
 * Render a migration module (`.mjs`) for a {@link MigrationPlan}.
 * Destructive steps are emitted commented-out; warnings become a review note at the top.
 */
export function renderMigrationSource(plan: MigrationPlan, opts: RenderMigrationOptions): string {
  const lines: string[] = [];
  lines.push(
    "// Generated by `cyphra migrate dev`. Review it before applying to shared databases.",
  );
  if (plan.warnings.length) {
    lines.push("//", "// REVIEW:");
    for (const w of plan.warnings) lines.push(...indentComment(`- ${w}`, ""));
  }
  if (plan.notes?.length) {
    lines.push("//", "// NOTES:");
    for (const n of plan.notes) lines.push(...indentComment(`- ${n}`, ""));
  }
  lines.push(
    `import { defineMigration } from ${JSON.stringify(opts.runtimeImport ?? "cyphra")};`,
    "",
  );
  lines.push("export default defineMigration({");
  lines.push(`  name: ${JSON.stringify(opts.name)},`);
  lines.push("  async up({ db }) {");
  if (plan.steps.length === 0) {
    lines.push("    // Nothing to do: write your own steps here.");
  }
  plan.steps.forEach((step, i) => {
    if (i > 0) lines.push("");
    lines.push(...indentComment(step.comment, "    "));
    if (step.kind === "statement") {
      lines.push(`    ${call(step.cypher, step.params)}`);
    } else if (step.kind === "guard") {
      lines.push("    {");
      lines.push(`      const [row] = await db.execute(${JSON.stringify(step.countCypher)});`);
      lines.push("      if (row && Number(row.count) > 0) {");
      lines.push(
        `        throw new Error(${JSON.stringify(step.message)} + \` (\${row.count} nodes)\`);`,
      );
      lines.push("      }");
      lines.push("    }");
    } else {
      lines.push("    // DESTRUCTIVE: uncomment to apply.");
      lines.push(`    // ${call(step.cypher)}`);
    }
  });
  lines.push("  },");
  lines.push("});", "");
  return lines.join("\n");
}
