import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { resolveSchema } from "../../model.js";
import { parseSchema } from "../../parseSchema.js";
import { renderCyphraGenSource } from "../../renderCyphraGen.js";
import { renderZodSource } from "../../renderZod.js";
import { validateSchema } from "../../validate.js";
import { convertPrismaSchema } from "./convert.js";
import { formatPrismaImportReport, printPrismaImport } from "./index.js";

const FIXTURES = join(import.meta.dirname, "__fixtures__");

describe.each(["blog", "shop", "saas"])("golden: %s", (name) => {
  it("converts to the expected schema and report", async () => {
    const body = await readFile(join(FIXTURES, `${name}.prisma`), "utf8");
    const result = convertPrismaSchema([{ name: `${name}.prisma`, body }]);
    const schema = printPrismaImport(result);
    await expect(schema).toMatchFileSnapshot(join(FIXTURES, `${name}.cyphra`));
    await expect(`${formatPrismaImportReport(result.issues)}\n`).toMatchFileSnapshot(
      join(FIXTURES, `${name}.report.txt`),
    );

    // Round trip: the output parses, validates, resolves and generates a client and zod schemas.
    const doc = parseSchema(schema);
    validateSchema(doc);
    const model = resolveSchema(doc);
    expect(model.nodes.length).toBeGreaterThan(0);
    expect(renderCyphraGenSource(doc)).toContain("Generated by `cyphra generate`");
    expect(renderZodSource(doc, { omitGenerated: true })).toContain("CreateInputSchema");
  });
});
