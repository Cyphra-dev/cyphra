import { readFile } from "node:fs/promises";
import { join } from "node:path";
import ts from "typescript";
import { describe, expect, it } from "vitest";
import { resolveSchema } from "../../model.js";
import { parseSchema } from "../../parseSchema.js";
import { renderCyphraGenSource } from "../../renderCyphraGen.js";
import { renderZodSource } from "../../renderZod.js";
import { validateSchema } from "../../validate.js";
import { convertNeogmaModels } from "./convert.js";
import { formatNeogmaImportReport, printNeogmaImport } from "./index.js";

const FIXTURES = join(import.meta.dirname, "__fixtures__");

/** Fixture name, and whether it uses legacy (experimental) decorators. */
const SETS = [
  ["shop", false],
  ["social", true],
  ["legacy-v1", false],
] as const;

describe.each(SETS)("golden: %s", (name, legacyDecorators) => {
  const file = join(FIXTURES, name, "models.ts");

  it("is valid neogma code (type-checks against the installed neogma)", () => {
    const program = ts.createProgram([file], {
      strict: true,
      noEmit: true,
      target: ts.ScriptTarget.ES2022,
      module: ts.ModuleKind.ESNext,
      moduleResolution: ts.ModuleResolutionKind.Bundler,
      lib: ["lib.es2022.d.ts", "lib.esnext.decorators.d.ts", "lib.dom.d.ts"],
      skipLibCheck: true,
      types: [],
      experimentalDecorators: legacyDecorators,
    });
    const errors = ts
      .getPreEmitDiagnostics(program)
      .map((d) => ts.flattenDiagnosticMessageText(d.messageText, "\n"));
    expect(errors).toEqual([]);
  }, 60_000);

  it("converts to the expected schema and report", async () => {
    const body = await readFile(file, "utf8");
    const result = convertNeogmaModels([{ name: `${name}/models.ts`, body }], { typescript: ts });
    const schema = printNeogmaImport(result);
    await expect(schema).toMatchFileSnapshot(join(FIXTURES, `${name}.cyphra`));
    await expect(`${formatNeogmaImportReport(result.issues)}\n`).toMatchFileSnapshot(
      join(FIXTURES, `${name}.report.txt`),
    );

    // Round trip: the output parses, validates, resolves and generates a client and zod schemas.
    const doc = parseSchema(schema);
    validateSchema(doc);
    const model = resolveSchema(doc);
    expect(model.nodes.length).toBeGreaterThan(0);
    expect(renderCyphraGenSource(doc)).toContain("Generated by `cyphra generate`");
    expect(renderZodSource(doc, { omitGenerated: true })).toContain("CreateInputSchema");
  });
});
